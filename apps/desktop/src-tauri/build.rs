fn main() {
    // Listing the app's commands turns on the ACL for them: each window may then call only the
    // commands its capability in `capabilities/` allows, instead of every window calling all.
    let manifest = tauri_build::AppManifest::new().commands(&[
        "overlay_present",
        "overlay_set_hit",
        "overlay_set_frame",
        "overlay_painted",
        "overlay_hide",
        "overlay_engage",
        "pin_open",
        "pin_init",
        "pin_show",
        "pin_painted",
        "pin_resize",
        "pin_drag",
        "pin_engage",
        "pin_close",
        "pin_cancel",
        "pin_set_fixed",
        "set_trigger_shortcut",
        "pause_trigger_shortcut",
        "set_ocr_shortcut",
        "ocr_start",
        "ocr_complete",
        "ocr_present",
        "ocr_cancel",
        "ocr_screen_permission",
        "ocr_request_screen_permission",
        "ocr_open_screen_settings",
        "ocr_lightbox_open",
        "ocr_lightbox_peek",
        "ocr_lightbox_close",
        "recent_apps",
        "autostart_enabled",
        "set_autostart",
        "accessibility_permission",
        "accessibility_request",
        "accessibility_open_settings",
        "secret_get",
        "secret_set",
        "secret_delete",
        "open_settings",
        "open_logs",
    ]);
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(manifest)).expect("failed to run tauri-build");
}
